def seed():
    Base.metadata.create_all(bind=engine)
    db = SessionLocal()
    try:
        existing = {s.name for s in db.query(models.Station).all()}
        inserted = 0
        for line_order, name, district, segment, lat, lng in PLACEHOLDER_STATIONS:
            if name in existing:
                continue
            db.add(
                models.Station(
                    name=name,
                    district=district,
                    segment=segment,
                    lat=lat,
                    lng=lng,
                    line_order=line_order,
                    data_source="seed_placeholder_coords_official_names",
                )
            )
            inserted += 1
        db.commit()
        print(f"시드 완료: {inserted}개 신규 정류장 삽입 (총 {len(PLACEHOLDER_STATIONS)}개, 45개 정거장 전체 반영)")
    finally:
        db.close()


if __name__ == "__main__":
    seed()
